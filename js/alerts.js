/* ── Cálculo de intervalo (km) según tipo de vehículo y mantenimiento ── */
function getAlertIntervalo(tipoVehiculo, tipoMantenimiento) {
  const tv = String(tipoVehiculo || '').toLowerCase();
  const isMoto = tv.includes('motocicleta') || tv === 'moto' || tv === 'motocicletas';
  const tm = String(tipoMantenimiento || '').toLowerCase();

  if (tm.includes('llanta delantera')) return 5000;
  if (tm.includes('llanta trasera')) return 10000;
  if (tm.includes('llanta')) return 35000;
  if (tm.includes('aceite')) return isMoto ? 1500 : 5000;
  return 0;
}

/* ── Próximo km de mantenimiento (siguiente múltiplo del intervalo) ── */
function getNextKm(currentKm, intervaloKm) {
  const km = parseFloat(currentKm) || 0;
  const it = parseFloat(intervaloKm) || 1;
  return (Math.floor(km / it) + 1) * it;
}

/* ── Semáforo por km restantes ── */
function getAlertSeverity(a) {
  const remaining = parseFloat(a.remainingKm) || (parseFloat(a.nextKm) - parseFloat(a.currentKm)) || 0;
  if (a.estado === 'Completada') return 'completed';
  if (remaining < 0) return 'critical';
  if (remaining < 500) return 'danger';
  if (remaining <= 1000) return 'warning';
  return 'success';
}

function severityInfo(sev) {
  return {
    success:  { color:'green', label:'Verde',   css:'sev-green',  icon:'🟢' },
    warning:  { color:'yellow',label:'Amarillo',css:'sev-yellow', icon:'🟡' },
    danger:   { color:'red',   label:'Rojo',    css:'sev-red',    icon:'🔴' },
    critical: { color:'red',   label:'Crítico', css:'sev-critical',icon:'⛔' },
    completed:{ color:'green', label:'Completada', css:'sev-green', icon:'✅' },
    info:     { color:'blue',  label:'Info',    css:'sev-blue',   icon:'🔵' },
  }[sev] || { color:'blue', label:'Info', css:'sev-blue', icon:'🔵' };
}

function getEstados() { return ['Pendiente','Próxima','Vencida','Completada']; }
function getTiposVehiculo() { return ['Motocicleta','Carro','Camión','Camioneta','Otro']; }
function getTiposMantenimiento() {
  return ['Cambio de llanta delantera','Cambio de llanta trasera','Cambio de llantas','Cambio de aceite'];
}

