    if (alert) {
      const code = String(alert.vehiculo || '').trim();
      selAsset = assets.find(a => a.code === code) || null;
    }

    const currentKm = selAsset ? selAsset.currentKm : (alert ? alert.currentKm : 0);
    const tipoMantenimiento = alert ? (alert.tipoMantenimiento || 'Cambio de aceite') : 'Cambio de aceite';
    const estado = alert ? (alert.estado || 'Pendiente') : 'Pendiente';
